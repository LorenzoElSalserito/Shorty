#!/usr/bin/env node
// Release step: download the Public Suffix List and compile it into a PHP array
// (public/lib/security/psl/rules.php). Never fetched at runtime.
// Unicode rules are dropped: Shorty accepts ASCII hostnames only and rejects punycode.
import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'public/lib/security/psl')
const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat'
const TESTS = 'https://raw.githubusercontent.com/publicsuffix/list/main/tests/tests.txt'

const fromFile = process.argv[2]
const text = fromFile ? readFileSync(fromFile, 'utf8') : await (await fetch(SOURCE)).text()
if (!text.includes('===BEGIN ICANN DOMAINS===')) throw new Error('Unexpected PSL content')

const rules = {}
let section = 0
for (const raw of text.split('\n')) {
  const line = raw.trim()
  if (line.includes('===BEGIN ICANN DOMAINS===')) section = 1
  if (line.includes('===BEGIN PRIVATE DOMAINS===')) section = 2
  if (!line || line.startsWith('//')) continue
  const rule = line.split(/\s/)[0].toLowerCase()
  if (!/^[!*a-z0-9._-]+$/.test(rule) || /(^|\.)xn--/.test(rule)) continue
  rules[rule] = section || 1
}
const count = Object.keys(rules).length
if (count < 5000) throw new Error(`PSL too small (${count} rules)`)

const php = '<?php\n// Generated by tools/update-psl.mjs from ' + SOURCE + ' (MPL-2.0). Do not edit.\nreturn [\n' +
  Object.entries(rules).map(([r, s]) => `'${r}'=>${s},`).join('\n') + '\n];\n'
mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'rules.php'), php)
writeFileSync(join(out, 'METADATA.json'), JSON.stringify({
  source: SOURCE,
  license: 'MPL-2.0',
  fetched_at: new Date().toISOString(),
  sha256: createHash('sha256').update(text).digest('hex'),
  rules: count,
}, null, 2) + '\n')

if (!fromFile || !existsSync(join(root, 'tests/fixtures/psl-tests.txt'))) {
  try {
    const t = await (await fetch(TESTS)).text()
    mkdirSync(join(root, 'tests/fixtures'), { recursive: true })
    writeFileSync(join(root, 'tests/fixtures/psl-tests.txt'), t)
  } catch (e) {
    console.warn('PSL test vectors not refreshed:', e.message)
  }
}
console.log(`PSL compiled: ${count} ASCII rules`)
