#!/usr/bin/env node
// Writes DEPENDENCIES.md: runtime dependency inventory (name, version, license).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'))
const composer = JSON.parse(readFileSync(join(root, 'composer.lock'), 'utf8'))

const rows = []
const seen = new Set()
const walk = (name) => {
  if (seen.has(name)) return
  seen.add(name)
  const entry = lock.packages[`node_modules/${name}`]
  if (!entry) return
  const manifest = join(root, 'node_modules', name, 'package.json')
  const license = entry.license || (existsSync(manifest) ? JSON.parse(readFileSync(manifest, 'utf8')).license : null)
  rows.push(['npm', name, entry.version, license || 'UNKNOWN'])
  Object.keys(entry.dependencies || {}).forEach(walk)
}
Object.keys(pkg.dependencies).forEach(walk)
for (const p of composer.packages) rows.push(['composer', p.name, p.version, (p.license || []).join(' OR ')])

const md = ['# Runtime dependencies', '', 'Generated by `tools/dependencies.mjs` from the lockfiles.', '',
  '| Ecosystem | Package | Version | License |', '|---|---|---|---|',
  ...rows.sort((a, b) => a[1].localeCompare(b[1])).map((r) => `| ${r.join(' | ')} |`), '']
writeFileSync(join(root, 'DEPENDENCIES.md'), md.join('\n'))
const bad = rows.filter((r) => !/MIT|BSD|ISC|Apache|MPL|AGPL|0BSD|CC0/i.test(r[3]))
if (bad.length) {
  console.error('Licenses needing review:', bad)
  process.exit(1)
}
console.log(`DEPENDENCIES.md: ${rows.length} runtime packages`)
